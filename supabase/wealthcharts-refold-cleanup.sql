-- ===========================================================================
-- Remove every WealthCharts row the fixed fold does not produce
--
-- Run in the Supabase SQL editor, THEN re-import all nine exports.
-- Safe to re-run: a second run matches nothing.
--
--
-- WHY NOT JUST ERASE EVERYTHING AND START AGAIN
--
-- Because deleting a trade takes its conversation with it. trade_reviews
-- references trades ON DELETE CASCADE, so wiping the journal would destroy
-- every mentor reply attached to it - including the thread that was tested on
-- 17 August. It would also lose shared_with_mentor, chart_url, and any notes
-- typed onto an imported row.
--
-- So this deletes by name, and only rows that are unmistakably a WealthCharts
-- import that the corrected fold no longer produces.
--
--
-- WHY "NOT IN THE GOOD LIST" RATHER THAN A LIST OF BAD ONES
--
-- A list of bad ids only knows about the exports in hand. Anything left behind
-- by an earlier import - a file since overwritten, a range no longer exported -
-- would survive it, and would be wrong in exactly the same way, because it was
-- folded by the same broken pairing.
--
-- Inverting it covers those too: whatever is not in the corrected set, on these
-- accounts, in this format, should not be there.
--
--
-- WHAT IT CANNOT TOUCH
--
-- The external_id pattern is two 17-character WealthCharts order ids joined by
-- a hyphen. A hand-logged trade has no external_id at all, and an import from
-- any other broker does not look like this. Neither is matched.
--
--
-- RUN SECTION 1 FIRST AND READ IT. It is a SELECT and changes nothing.
-- ===========================================================================


